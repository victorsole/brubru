"""One-shot generator: emit the v2 "European Commission" domain modules by
copy-pasting the v1 Commission route decorators + signatures verbatim and
delegating the body to the v1 handler (single source of truth during v1+v2
coexistence). Same approach as scripts/_gen_v2_parliament.py.

Section A only (16 core Commission routes), excluding multi-institution
endpoints. Two wrinkles vs the EP generator:
- the commissioners source spans TWO v1 modules (the *list* lives in
  api.v1.metadata, the detail + agenda in api.v1.commissioners);
- metadata's list_commissioners is decorated at the absolute path
  "/commissioners" (its router has no prefix), so its decorator path is
  overridden to "" to sit under the /commissioners-prefixed v2 router.

Only the 7 Commission-domain `/api/v1/<seg>` example URLs are rewritten to
`/api/v2/commission/<seg>`; cross-domain refs (funding, acts, metadata
siblings, parliamentary-questions, specialised/*) are left pointing at v1.

Run once from backend/:  python3.12 scripts/_gen_v2_commission.py
"""
