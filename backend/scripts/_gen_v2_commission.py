# Longest-first where prefixes overlap (commission-register-documents before
# commission-register) so the alternation matches the longer segment first.
EC_SEGMENTS = (
    "commissioners", "commission-register-documents", "commission-register",
    "meetings", "rsb-opinions", "infringements", "consultations",
    "tris-notifications",
)
_URL_RE = re.compile(r"/api/v1/(" + "|".join(EC_SEGMENTS) + r")\b")


def rewrite_urls(text: str) -> str:
    return _URL_RE.sub(r"/api/v2/commission/\1", text)


