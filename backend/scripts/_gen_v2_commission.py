def param_names(fn: ast.AsyncFunctionDef) -> list[str]:
    a = fn.args
    return [p.arg for p in (a.posonlyargs + a.args + a.kwonlyargs)]


def parse_module(mod: str):
    src = (V1 / f"{mod}.py").read_text()
    tree = ast.parse(src)
    funcs = {n.name: n for n in ast.walk(tree) if isinstance(n, ast.AsyncFunctionDef)}
    # top-level defined names (classes + module assignments) — needed to know
    # which underscore-prefixed names `import *` will skip and must be imported.
    defined = set()
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            defined.add(node.name)
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    defined.add(t.id)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            defined.add(node.target.id)
    return src, src.splitlines(), funcs, defined


def override_path(deco: str, new_path: str) -> str:
    # replace the first quoted string after `.get(` with new_path
    return re.sub(r'(\.get\(\s*)(["\'])[^"\']*\2', rf'\1"{new_path}"', deco, count=1)


def build_module(name: str, conf: dict) -> str:
    mods = []
    for m, _ in conf["groups"]:
        if m not in mods:
            mods.append(m)

    cache = {m: parse_module(m) for m in mods}

    # Build the route bodies first so we can detect which underscore-prefixed
    # names (skipped by `import *`) must be explicitly imported.
    bodies = []
    underscore_imports: dict[str, set] = {m: set() for m in mods}
    for mod, funcs_spec in conf["groups"]:
        src, lines, funcs, defined = cache[mod]
        for fname, path_ovr in funcs_spec:
            fn = funcs[fname]
            decos = []
            for d in fn.decorator_list:
                seg = ast.get_source_segment(src, d)
                seg = "@" + seg if not seg.startswith("@") else seg
                seg = re.sub(r"@\w+\.get\(", "@router.get(", seg)  # normalise router var
                if path_ovr is not None:
                    seg = override_path(seg, path_ovr)
                decos.append(rewrite_urls(seg))
            sig = "\n".join(lines[fn.lineno - 1: fn.body[0].lineno - 1])
            call = ", ".join(f"{n}={n}" for n in param_names(fn))
            chunk = "\n".join(decos) + "\n" + sig + f"\n    return await _v1_{mod}.{fname}({call})"
            for tok in set(re.findall(r"\b_[A-Za-z0-9_]+\b", "\n".join(decos) + "\n" + sig)):
                if tok in defined:
                    underscore_imports[mod].add(tok)
            bodies.append(chunk)

    out = [PREAMBLE_HEAD.format(prefix="/api/v2/commission" + conf["prefix"])]
    for m in mods:
        out.append(f"from api.v1 import {m} as _v1_{m}")
    for m in mods:
        out.append(f"from api.v1.{m} import *  # noqa: F401,F403 - reproduce v1 namespace for get_type_hints")
        if underscore_imports[m]:
            names = ", ".join(sorted(underscore_imports[m]))
            out.append(f"from api.v1.{m} import {names}  # private names skipped by import *")
    out.append("")
    out.append(f'router = APIRouter(prefix="{conf["prefix"]}", tags=["{conf["tag"]}"])')
    out.append("")
    out.append("")
    for chunk in bodies:
        out.append(chunk)
        out.append("")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, conf in OUTPUTS.items():
        (OUT / f"{name}.py").write_text(build_module(name, conf))
        print(f"[OK] wrote api/v2/commission/{name}.py")


if __name__ == "__main__":
    main()
