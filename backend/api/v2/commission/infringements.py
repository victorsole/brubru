def _bad_request(message: str) -> HTTPException:
    return HTTPException(status_code=422, detail={"error": message, "reason_code": "invalid_query"})


def _not_found(resource: str, value: str) -> HTTPException:
    return HTTPException(status_code=404, detail={"error": f"{resource} not found: {value}",
                                                  "reason_code": "not_found", "resource": resource, "id": value})


def _member_state(value: Optional[str]) -> Optional[str]:
    if value is None or not value.strip():
        return None
    code = iel.MEMBER_STATE_ALIASES.get(value.strip().upper(), value.strip().upper())
    if code == "GB":
        code = "UK"
    if code not in _REGISTER_MEMBER_STATES:
        raise _bad_request(f"member_state must be one of {', '.join(sorted(_REGISTER_MEMBER_STATES))} (Greece is EL)")
    return code


def _case_type(value: Optional[str]) -> Optional[str]:
    if value is None or not value.strip():
        return None
    v = value.strip()
    if v.upper() in _CASE_TYPES:
        return _CASE_TYPES[v.upper()]
    for label in _CASE_TYPES.values():
        if label.lower() == v.lower():
            return label
    raise _bad_request(f"case_type must be one of {', '.join(_CASE_TYPES)} "
                       "(non-communication, non-conformity, bad application, regulations/treaties/decisions)")


def _normalise_number(value: str) -> str:
    return "".join(value.split()).upper()


def _range(where: list, params: dict, column: str, start: Optional[date], end: Optional[date]) -> None:
    if start and end and start > end:
        raise _bad_request("decision_from is after decision_to")
    if start:
        where.append(f"{column} >= :d_from"); params["d_from"] = start
    if end:
        where.append(f"{column} <= :d_to"); params["d_to"] = end


def _decision_from_row(r) -> InfringementDecision:
    r = dict(r)
    r["policy_areas"] = list(r.get("policy_areas") or [])
    r["document_date"] = r["decision_date"]
    return InfringementDecision(**r)


