@router.get(
    "",
    response_model=PaginatedResponse[InfringementCase],
    summary="Infringement cases against Member States (open and closed, since 1987)",
    description=f"""**What it does**
Lists infringement cases: the legal proceedings the European Commission opens when it considers a Member State has failed to apply EU law. One item per case, with the Member State, the type of infringement (non-communication of transposition measures, non-conformity, bad application), the Commission department in charge, the subject, whether the case is still open, and its latest step (letter of formal notice, reasoned opinion, referral to the Court of Justice, closure).

**When to use it**
To see which Member States face proceedings on a topic, how far each case has gone, and which are still open. Filter by `member_state`, `active`, `case_type`, `lead_dg` or `policy_area`, search the subject with `q`, or window on the latest decision date.

**Input**
- `member_state`: code as the Commission writes it, e.g. `PL`, `EL` (Greece; `GR` is accepted), `UK`.
- `active`: `true` for open cases, `false` for closed ones.
- `case_type`: `NCM` (non-communication), `NCF` (non-conformity), `BAD` (bad application), `REG` (regulations, Treaties and decisions).
- `lead_dg`: department code, e.g. `ENV`, `GROW`, `MOVE`.
- `policy_area`: text contained in a policy area, e.g. `waste`.
- `latest_decision_category`: e.g. `RTC` for cases whose latest step is a referral to the Court.
- `q`: words in the subject, or an infringement number.
- `decision_from`, `decision_to`: bounds on the latest decision date (YYYY-MM-DD).
{SYNC_PARAMS_DOC}
- `order`: `recent` (default, latest decision first), `oldest`, or a sync order: `updated_asc`, `updated_desc`, `created_asc`, `created_desc`. `limit` (default 100, max 500), `page`.

**Try it**
```
GET /api/v2/commission/infringements?member_state=PL&active=true
GET /api/v2/commission/infringements?case_type=NCM&lead_dg=ENV&active=true
GET /api/v2/commission/infringements?q=nitrates
GET /api/v2/commission/infringements?updated_from=2026-09-21&order=updated_asc&limit=500
```

**You get back**
A paginated list of cases. Each carries `id`, `infringement_number`, `member_state`, `active_case`, `case_type`, `lead_dg`, `title`, `first_decision_date`, `latest_decision_date`, `latest_decision_type`, `decision_count`, `court_cases`, `press_release_urls`, and the five datapoints (`public_url`, `body_txt`, `body_html`, `document_date`, `creation_date`; the bodies are on the detail endpoint). {SYNC_FIELDS_DOC}

**Data freshness**
{_SOURCE}""",
)
def list_cases(
    request: Request,
    member_state: Optional[str] = Query(None, description="Member State code, e.g. PL, EL (Greece), UK."),
    active: Optional[bool] = Query(None, description="true for open cases, false for closed ones."),
    case_type: Optional[str] = Query(None, description="NCM | NCF | BAD | REG."),
    lead_dg: Optional[str] = Query(None, description="Commission department code, e.g. ENV."),
    policy_area: Optional[str] = Query(None, description="Text contained in a policy area."),
    latest_decision_category: Optional[str] = Query(None, description="e.g. LFN, RO, RTC, CLOSURES."),
    q: Optional[str] = Query(None, description="Words in the subject, or an infringement number."),
    decision_from: Optional[date] = Query(None, description="Latest decision on or after (YYYY-MM-DD)."),
    decision_to: Optional[date] = Query(None, description="Latest decision on or before (YYYY-MM-DD)."),
    created_from: Optional[datetime] = Query(None, description="First recorded by Brubru on or after (ISO date or datetime)."),
    created_to: Optional[UpperBoundDatetime] = Query(None, description="First recorded on or before; a bare date covers the whole day."),
    updated_from: Optional[datetime] = Query(None, description="Content last changed on or after. The incremental-sync filter."),
    updated_to: Optional[UpperBoundDatetime] = Query(None, description="Content last changed on or before; a bare date covers the whole day."),
    order: str = Query("recent", pattern="^(recent|oldest|updated_asc|updated_desc|created_asc|created_desc)$"),
    limit: int = Query(100, ge=1, le=500, description="Items per page (default 100, max 500)."),
    page: int = Query(1, ge=1),
    user: User = Depends(api_user_with_rate_limit),
    db: Session = Depends(get_db),
) -> PaginatedResponse[InfringementCase]:
    where, params = [], {}
    ms = _member_state(member_state)
    if ms:
        where.append("member_state = :ms"); params["ms"] = ms
    if active is not None:
        where.append("active_case = :active"); params["active"] = active
    ct = _case_type(case_type)
    if ct:
        where.append("case_type = :ct"); params["ct"] = ct
    if lead_dg:
        where.append("upper(lead_dg_code) = :dg"); params["dg"] = lead_dg.strip().upper()
    if policy_area:
        where.append("EXISTS (SELECT 1 FROM unnest(policy_areas) p WHERE p ILIKE :pa)"); params["pa"] = f"%{policy_area.strip()}%"
    if latest_decision_category:
        where.append("latest_decision_category = :cat"); params["cat"] = latest_decision_category.strip().upper()
    if q:
        where.append("(title ILIKE :q OR infringement_number ILIKE :qn)")
        params["q"] = f"%{q.strip()}%"; params["qn"] = f"%{_normalise_number(q)}%"
    _range(where, params, "latest_decision_date", decision_from, decision_to)
    sql_window(where, params, validate_window(created_from, created_to, updated_from, updated_to),
               "creation_date", "content_updated_at")
    clause = ("WHERE " + " AND ".join(where)) if where else ""
    direction = "DESC" if order == "recent" else "ASC"
    ordering = sql_order(order, "creation_date", "content_updated_at") \
        or f"latest_decision_date {direction} NULLS LAST, id {direction}"
    total = int(db.execute(text(f"SELECT count(*) FROM infringement_cases {clause}"), params).scalar() or 0)
    rows = db.execute(text(
        f"SELECT {_CASE_COLS} FROM infringement_cases {clause} "
        f"ORDER BY {ordering} LIMIT :limit OFFSET :offset"),
        {**params, "limit": limit, "offset": (page - 1) * limit}).mappings().all()
    items = []
    for r in rows:
        r = dict(r)
        for k in ("policy_areas", "court_cases", "press_release_urls"):
            r[k] = list(r.get(k) or [])
        r["document_date"] = r["latest_decision_date"]
        items.append(InfringementCase(**r))
    return build_envelope(items, total=total, page=page, limit=limit,
                          published_from=decision_from, published_to=decision_to,
                          op_core_title="Infringement cases", op_core_type="Infringement case",
                          op_core_identifier=str(request.url))


