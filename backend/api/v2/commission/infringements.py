def _load_case(db: Session, case_id: str):
    value = case_id.strip()
    if value.isdigit():
        row = db.execute(text(f"SELECT {_CASE_COLS}, body_txt, body_html, body_source FROM infringement_cases WHERE id = :id"),
                         {"id": int(value)}).mappings().first()
        if row:
            return row
    return db.execute(text(f"SELECT {_CASE_COLS}, body_txt, body_html, body_source FROM infringement_cases "
                           "WHERE infringement_number = :n"), {"n": _normalise_number(value)}).mappings().first()


